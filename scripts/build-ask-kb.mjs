// Writes ask-api/lib/knowledge.mjs (and a readable knowledge.md beside it)
// from the site's own data. Runs before every build so the assistant and
// the pages always agree.
import { build } from "esbuild";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tmp = resolve(root, "node_modules/.cache/ask-kb.mjs");

await build({
  entryPoints: [resolve(root, "scripts/ask-kb.ts")],
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: tmp,
  alias: { "@": resolve(root, "src") },
  logLevel: "error",
});

const { buildKnowledge } = await import(pathToFileURL(tmp).href + `?t=${Date.now()}`);
const text = buildKnowledge();
rmSync(tmp, { force: true });

const dir = resolve(root, "ask-api/lib");
mkdirSync(dir, { recursive: true });
writeFileSync(resolve(dir, "knowledge.md"), text + "\n");
writeFileSync(
  resolve(dir, "knowledge.mjs"),
  `// Generated by scripts/build-ask-kb.mjs from the site's data. Do not edit by hand.\nexport default ${JSON.stringify(text)};\n`,
);
console.log(`ask-kb: ${text.length.toLocaleString()} characters, ~${Math.round(text.length / 4).toLocaleString()} tokens`);
